#!/usr/bin/env bash
# Reproduce every figure, table and quoted number of the paper and of its supplement.
#
#   ./reproduce_paper.sh          run the tests and all the experiments, and make all the
#                                 figures (about 2 h 10 min on a 4-core machine)
#   ./reproduce_paper.sh plots    only redraw the figures from the stored results (about 1 min)
#
# Times. They are those of the last full run, on a 4-core machine: 92 min for the steps up
# to "radial validation", and 9 and 26 min for the two steps after it, which were run
# separately. They are approximate and machine dependent.
#
# The step titles give the item of the paper (numbers of the draft in ../paper/: main.pdf and,
# with the prefix S, supplement.pdf), the output file and the time. The complete table is in
# experiments/paper/README.md. Data: results/ and results/paper/; figures: figures/ and
# figures/paper/.
#
# Run from numerics/. Uses the Python in ../.venv if it exists, else python3.
set -euo pipefail
cd "$(dirname "$0")"
PY=../.venv/bin/python
[ -x "$PY" ] || PY=python3
export OMP_NUM_THREADS=1 PYTHONPATH="$PWD${PYTHONPATH:+:$PYTHONPATH}"

step() { echo; echo "=== $* ==="; }

if [ "${1:-all}" = "plots" ]; then
  # Figures A1, A2, A4 (not in the paper) need the node histories (*.npz), which are not in
  # git: they are regenerated by 'meshes run' (~2 min).
  ls results/paper/A_mesh_*.npz >/dev/null 2>&1 || { step "A: meshes (node histories)"; $PY -m experiments.paper.meshes run; }
  for m in meshes convergence limit_examples tw_error transient variable_w0 work_precision; do step "plot $m"; $PY -m experiments.paper.$m plot; done
  step "Figure 1, A5_mesh_snapshots.png (runs two short simulations)"; $PY -m experiments.paper.mesh_snapshots
  step "Figure 4, tw_instability.png, and the other figures of the BDF experiments"; $PY -m experiments.plots
  exit 0
fi

step "tests, ~15 s";                                        $PY -m pytest -q
step "Table 1 (tab:speedcoef) -> speed_coefficient.json, ~5 s"; $PY -m experiments.paper.speed_coefficient
step "Eq. (37) (an:eq:solv), averaged truncation error -> truncation_check.json, ~10 s"; $PY -m experiments.truncation_check
step "Sections 6.6 and S1: inside the hypotheses of the travelling-wave theorem -> G_*.json, ~45 s"; $PY -m experiments.paper.in_hypotheses
step "Section 6.5: setting of the convergence theorem -> H_convergence_thm.json, ~25 s"; $PY -m experiments.paper.convergence_thm
step "Figure 1 -> A5_mesh_snapshots.png, ~5 s"; $PY -m experiments.paper.mesh_snapshots
step "Section 6.1: nodes and remeshings -> A_meshes.json (figures A1-A4: not in the paper), ~3 min"; $PY -m experiments.paper.meshes
step "Figures S1-S3, drag ratios -> D_tw_error.json, D1-D3_*.png (D4, D5: not in the paper), ~8 min"; $PY -m experiments.paper.tw_error
step "Figure S4, M_T, lattice phases -> E_transient.json, D6_transients.png, ~33 min"; $PY -m experiments.paper.transient
step "Figure 5 -> B_convergence.json, B4_radial_extinction_dt.png (B1-B3: not in the paper), ~3 min"; $PY -m experiments.paper.convergence
# (Figure 2 also reads results/limit_comparison.json, which is regenerated two steps below.)
step "Figures 2 and 6 -> C1_ale_vs_limit.png, C2_self_similar_convergence.png (C3: not in the paper), ~13 min"; $PY -m experiments.paper.limit_examples
step "Figure 4 (data; drawn in the last step) -> results/traveling_wave.json, ~21 min"; $PY -m experiments.traveling_wave
step "Table 2 (tab:limit) -> results/limit_comparison.json, ~8 min"; $PY -m experiments.limit_comparison
step "radial validation with BDF (not in the paper) -> results/radial.json, ~1 min"; $PY -m experiments.radial
step "Figure 3 -> I_variable_w0.json, I1_variable_w0.png, ~9 min"; $PY -m experiments.paper.variable_w0
step "Figure S5, Table S1 (tab:work) -> J_work_precision.json, J1_work_precision.png, ~26 min"; $PY -m experiments.paper.work_precision
step "Figure 4 -> tw_instability.png, and the other figures of the BDF experiments, ~5 s"; $PY -m experiments.plots
echo; echo "Done. Figures in figures/ and figures/paper/, data in results/ and results/paper/."
